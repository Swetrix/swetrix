CREATE TABLE IF NOT EXISTS `data_export` (
  `id` varchar(36) NOT NULL,
  `projectId` varchar(12) NOT NULL,
  `ownerId` varchar(36) NOT NULL,
  `revision` varchar(36) NOT NULL,
  `gcpProjectId` varchar(63) NOT NULL,
  `datasetId` varchar(1024) NOT NULL,
  `location` varchar(64) NOT NULL,
  `tablePrefix` varchar(128) NOT NULL,
  `encryptedCredentials` text NOT NULL,
  `serviceAccountEmail` varchar(254) NOT NULL,
  `startDate` date NOT NULL,
  `nextDate` date NOT NULL,
  `enabled` boolean NOT NULL DEFAULT true,
  `status` varchar(16) NOT NULL DEFAULT 'idle',
  `nextSyncAt` datetime DEFAULT NULL,
  `lastSyncedDate` date DEFAULT NULL,
  `lastSyncedAt` datetime DEFAULT NULL,
  `lastRowCount` double NOT NULL DEFAULT 0,
  `lastError` varchar(500) DEFAULT NULL,
  `createdAt` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (`id`),
  UNIQUE KEY `IDX_data_export_project` (`projectId`),
  KEY `IDX_data_export_due` (`enabled`, `nextSyncAt`),
  CONSTRAINT `FK_data_export_project` FOREIGN KEY (`projectId`) REFERENCES `project` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
